    S.STATE_NAME,
    R.REGION_NAME
ORDER BY TOTAL_REVENUE DESC;


// Task 58: Region-wise Revenue Report

SELECT
    R.REGION_NAME,
    COUNT(DISTINCT BR.BRANCH_ID) AS NUM_BRANCHES,
    SUM(F.QUANTITY) AS TOTAL_QTY_SOLD,
    SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE,
    ROUND(AVG(F.TOTAL_AMOUNT),2) AS AVG_SALE_AMOUNT
FROM FACT_SALES F
JOIN DIM_BRANCH BR
    ON F.BRANCH_ID = BR.BRANCH_ID
JOIN DIM_CITY CT
    ON BR.CITY_ID = CT.CITY_ID
JOIN DIM_STATE S
    ON CT.STATE_ID = S.STATE_ID
JOIN DIM_REGION R
    ON S.REGION_ID = R.REGION_ID
GROUP BY R.REGION_NAME
ORDER BY TOTAL_REVENUE DESC;


// Task 59: Monthly Revenue Report

SELECT
    M.MONTH_NAME,
    Q.QUARTER_NAME,
    Y.YEAR_VALUE,
    SUM(F.TOTAL_AMOUNT) AS MONTHLY_REVENUE,
    SUM(F.QUANTITY) AS TOTAL_QTY_SOLD
FROM FACT_SALES F
JOIN DIM_DATE D
    ON F.DATE_ID = D.DATE_ID
JOIN DIM_MONTH M
    ON D.MONTH_ID = M.MONTH_ID
JOIN DIM_QUARTER Q
    ON M.QUARTER_ID = Q.QUARTER_ID
JOIN DIM_YEAR Y
    ON Q.YEAR_ID = Y.YEAR_ID
GROUP BY
    M.MONTH_NAME,
    Q.QUARTER_NAME,
    Y.YEAR_VALUE
ORDER BY
    Y.YEAR_VALUE,
    M.MONTH_NAME;


// Task 60: Quarterly Revenue Report

SELECT
