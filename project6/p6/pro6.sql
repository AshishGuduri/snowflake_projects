    CT.CITY_NAME,
    S.STATE_NAME,
    R.REGION_NAME
ORDER BY TOTAL_REVENUE DESC;


// Task 57: State-wise Revenue Report

SELECT
    S.STATE_NAME,
    R.REGION_NAME,
    SUM(F.QUANTITY) AS TOTAL_QTY_SOLD,
    SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES F
JOIN DIM_BRANCH BR
    ON F.BRANCH_ID = BR.BRANCH_ID
JOIN DIM_CITY CT
    ON BR.CITY_ID = CT.CITY_ID
JOIN DIM_STATE S
    ON CT.STATE_ID = S.STATE_ID
JOIN DIM_REGION R
    ON S.REGION_ID = R.REGION_ID
