SELECT COUNT(*) AS TOTAL_SUBCATEGORIES FROM SNOW_DIM_SUBCATEGORY; 
SELECT COUNT(*) AS TOTAL_PRODUCTS FROM SNOW_DIM_PRODUCT;  

-- TASK 9 — Create Snowflake Schema Fact Table (`SNOW_FACT_SALES`) & Load Data
CREATE TABLE SNOW_FACT_SALES (
    SALES_KEY        NUMBER AUTOINCREMENT PRIMARY KEY,
    TRANSACTION_ID   VARCHAR(50),
    TRANSACTION_DATE DATE,
    CUSTOMER_ID      NUMBER,
    STORE_KEY        NUMBER REFERENCES SNOW_DIM_STORE(STORE_KEY),
    PRODUCT_KEY      NUMBER REFERENCES SNOW_DIM_PRODUCT(PRODUCT_KEY),
    QUANTITY         NUMBER,
    TOTAL_AMOUNT     NUMBER(12,2)
);

INSERT INTO SNOW_FACT_SALES (TRANSACTION_ID, TRANSACTION_DATE, CUSTOMER_ID, STORE_KEY, PRODUCT_KEY, QUANTITY, TOTAL_AMOUNT)
SELECT
    t.TRANSACTION_ID,
    t.TRANSACTION_DATE,
    t.CUSTOMER_ID,
    s.STORE_KEY,
    p.PRODUCT_KEY,
    t.QUANTITY,
    t.QUANTITY * t.UNIT_PRICE AS TOTAL_AMOUNT
FROM STG_SALES_TRANSACTIONS t
JOIN SNOW_DIM_STORE s   ON t.STORE_ID = s.STORE_ID
JOIN SNOW_DIM_PRODUCT p ON t.PRODUCT_ID = p.PRODUCT_ID;

SELECT COUNT(*) AS TOTAL_SALES_ROWS FROM SNOW_FACT_SALES;

-- TASK 10 — Star Schema Analytics Query (Single-Hop Join Performance)
SELECT
    d.REGION_NAME,
    p.CATEGORY_NAME,
    SUM(f.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM STAR_FACT_SALES f
JOIN STAR_DIM_STORE d   ON f.STORE_KEY = d.STORE_KEY
JOIN STAR_DIM_PRODUCT p ON f.PRODUCT_KEY = p.PRODUCT_KEY
GROUP BY d.REGION_NAME, p.CATEGORY_NAME
ORDER BY d.REGION_NAME, p.CATEGORY_NAME;

-- TASK 11 — Snowflake Schema Analytics Query (Multi-Hop Normalized Join)
SELECT
    r.REGION_NAME,
    c.CATEGORY_NAME,
    SUM(f.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM SNOW_FACT_SALES f
JOIN SNOW_DIM_STORE s        ON f.STORE_KEY = s.STORE_KEY
JOIN SNOW_DIM_REGION r        ON s.REGION_KEY = r.REGION_KEY
JOIN SNOW_DIM_PRODUCT p       ON f.PRODUCT_KEY = p.PRODUCT_KEY
JOIN SNOW_DIM_SUBCATEGORY sc  ON p.SUBCATEGORY_KEY = sc.SUBCATEGORY_KEY
JOIN SNOW_DIM_CATEGORY c      ON sc.CATEGORY_KEY = c.CATEGORY_KEY
GROUP BY r.REGION_NAME, c.CATEGORY_NAME
ORDER BY r.REGION_NAME, c.CATEGORY_NAME;

-- TASK 13 — Regional Manager Sales Performance Report
SELECT
    d.REGIONAL_MANAGER,
    SUM(f.QUANTITY)     AS TOTAL_ITEMS_SOLD,
    SUM(f.TOTAL_AMOUNT) AS TOTAL_SALES_AMOUNT
FROM STAR_FACT_SALES f
JOIN STAR_DIM_STORE d ON f.STORE_KEY = d.STORE_KEY
GROUP BY d.REGIONAL_MANAGER
ORDER BY TOTAL_SALES_AMOUNT DESC;

