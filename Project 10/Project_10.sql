-- TASK 13 — Display Complete Type 6 History
SELECT CUSTOMER_ID, CUSTOMER_NAME, CURRENT_MEMBERSHIP, PREVIOUS_MEMBERSHIP, EFFECTIVE_DATE, EXPIRY_DATE, IS_CURRENT
FROM DIM_CUSTOMER_TYPE6
ORDER BY CUSTOMER_ID, EFFECTIVE_DATE;

-- TASK 14 — Current Customer Report
SELECT
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CITY,
    CURRENT_MEMBERSHIP,
    PREVIOUS_MEMBERSHIP
FROM DIM_CUSTOMER_TYPE6
WHERE IS_CURRENT = TRUE
ORDER BY CUSTOMER_ID;

-- TASK 15 — Point-in-Time Historical Query
SELECT CUSTOMER_ID, CUSTOMER_NAME, CURRENT_MEMBERSHIP, EFFECTIVE_DATE, EXPIRY_DATE
FROM DIM_CUSTOMER_TYPE6
WHERE CUSTOMER_ID = 101
  AND '2026-03-15' BETWEEN EFFECTIVE_DATE AND EXPIRY_DATE;