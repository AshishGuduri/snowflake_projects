-- TASK 3: Dynamic Data Masking (DDM) Implementation
CREATE OR REPLACE MASKING POLICY MASK_SSN AS (VAL STRING) RETURNS STRING ->
    CASE WHEN CURRENT_ROLE() = 'COMPLIANCE_OFFICER' THEN VAL
         ELSE '***-**-' || RIGHT(VAL, 4)
    END;

CREATE OR REPLACE MASKING POLICY MASK_ACCOUNT AS (VAL STRING) RETURNS STRING ->
    CASE WHEN CURRENT_ROLE() = 'COMPLIANCE_OFFICER' THEN VAL
         ELSE 'ACT-****'
    END;

ALTER TABLE SILVER_BANK_TRANSACTIONS MODIFY COLUMN CLIENT_SSN SET MASKING POLICY MASK_SSN;
ALTER TABLE SILVER_BANK_TRANSACTIONS MODIFY COLUMN ACCOUNT_NO SET MASKING POLICY MASK_ACCOUNT;

USE ROLE NA_ANALYST;
USE WAREHOUSE COMPUTE_WH;
SELECT * FROM FINANCIAL_GOVERNANCE_DB.WEALTH_CORE.SILVER_BANK_TRANSACTIONS ORDER BY TXN_ID;

-- TASK 4: Row-Access Policy (RAP) Regional Isolation
USE ROLE ACCOUNTADMIN;
CREATE OR REPLACE ROW ACCESS POLICY RAP_REGION_POLICY AS (REGION_VAL STRING) RETURNS BOOLEAN ->
    CASE
        WHEN CURRENT_ROLE() = 'COMPLIANCE_OFFICER' THEN TRUE
        WHEN CURRENT_ROLE() = 'NA_ANALYST' AND REGION_VAL = 'NA' THEN TRUE
        WHEN CURRENT_ROLE() = 'EU_ANALYST' AND REGION_VAL = 'EU' THEN TRUE
        ELSE FALSE
    END;

ALTER TABLE SILVER_BANK_TRANSACTIONS ADD ROW ACCESS POLICY RAP_REGION_POLICY ON (REGION);

USE ROLE EU_ANALYST;
SELECT * FROM FINANCIAL_GOVERNANCE_DB.WEALTH_CORE.SILVER_BANK_TRANSACTIONS ORDER BY TXN_ID;

-- TASK 5: Secure Data Sharing & Clean Room Audit View
USE ROLE ACCOUNTADMIN;
GRANT CREATE VIEW ON SCHEMA FINANCIAL_GOVERNANCE_DB.WEALTH_CORE TO ROLE COMPLIANCE_OFFICER;

USE ROLE COMPLIANCE_OFFICER;
USE WAREHOUSE COMPUTE_WH;
USE SCHEMA FINANCIAL_GOVERNANCE_DB.WEALTH_CORE;

CREATE OR REPLACE SECURE VIEW SECURE_GOLD_EXTERNAL_AUDIT_SUMMARY AS
SELECT
    REGION,
    SUM(AMOUNT)          AS TOTAL_SETTLED_VAL,
    COUNT(*)             AS SETTLED_TXN_COUNT,
    ROUND(AVG(AMOUNT),2) AS AVG_SETTLED_AMOUNT
FROM SILVER_BANK_TRANSACTIONS
WHERE STATUS = 'SETTLED'
GROUP BY REGION
ORDER BY REGION;

GRANT SELECT ON VIEW SECURE_GOLD_EXTERNAL_AUDIT_SUMMARY TO ROLE COMPLIANCE_OFFICER;

SELECT * FROM SECURE_GOLD_EXTERNAL_AUDIT_SUMMARY ORDER BY TOTAL_SETTLED_VAL DESC;

