    B.BRAND_NAME,
    CAT.CATEGORY_NAME
ORDER BY TOTAL_REVENUE DESC;


// Task 55: Category-wise Revenue Report

SELECT
    CAT.CATEGORY_NAME,
    SUM(F.QUANTITY) AS TOTAL_QTY_SOLD,
    SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE,
    COUNT(*) AS TOTAL_TRANSACTIONS
FROM FACT_SALES F
JOIN DIM_PRODUCT P
    ON F.PRODUCT_ID = P.PRODUCT_ID
JOIN DIM_BRAND B
    ON P.BRAND_ID = B.BRAND_ID
JOIN DIM_CATEGORY CAT
    ON B.CATEGORY_ID = CAT.CATEGORY_ID
GROUP BY CAT.CATEGORY_NAME
ORDER BY TOTAL_REVENUE DESC;


// Task 56: City-wise Sales Report

SELECT
    CT.CITY_NAME,
    S.STATE_NAME,
    R.REGION_NAME,
    SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES F
JOIN DIM_BRANCH BR
    ON F.BRANCH_ID = BR.BRANCH_ID
JOIN DIM_CITY CT
    ON BR.CITY_ID = CT.CITY_ID
JOIN DIM_STATE S
    ON CT.STATE_ID = S.STATE_ID
JOIN DIM_REGION R
    ON S.REGION_ID = R.REGION_ID
