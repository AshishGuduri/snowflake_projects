    Y.YEAR_VALUE,
    SUM(F.TOTAL_AMOUNT) AS QUARTERLY_REVENUE,
    SUM(F.QUANTITY) AS TOTAL_QTY_SOLD
FROM FACT_SALES F
JOIN DIM_DATE D
    ON F.DATE_ID = D.DATE_ID
JOIN DIM_MONTH M
    ON D.MONTH_ID = M.MONTH_ID
JOIN DIM_QUARTER Q
    ON M.QUARTER_ID = Q.QUARTER_ID
JOIN DIM_YEAR Y
    ON Q.YEAR_ID = Y.YEAR_ID
GROUP BY
    Q.QUARTER_NAME,
    Y.YEAR_VALUE
ORDER BY
    Y.YEAR_VALUE,
    Q.QUARTER_NAME;


