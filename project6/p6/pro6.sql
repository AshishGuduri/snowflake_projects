// Task 65: Product Performance Report

SELECT
    P.PRODUCT_NAME,
    CAT.CATEGORY_NAME,
    B.BRAND_NAME,
    SUM(F.QUANTITY) AS UNITS_SOLD,
    SUM(F.TOTAL_AMOUNT) AS REVENUE,
    ROUND(AVG(F.TOTAL_AMOUNT),2) AS AVG_SALE_VALUE
FROM FACT_SALES F
JOIN DIM_PRODUCT P
    ON F.PRODUCT_ID = P.PRODUCT_ID
JOIN DIM_BRAND B
    ON P.BRAND_ID = B.BRAND_ID
JOIN DIM_CATEGORY CAT
    ON B.CATEGORY_ID = CAT.CATEGORY_ID
GROUP BY
    P.PRODUCT_NAME,
    CAT.CATEGORY_NAME,
    B.BRAND_NAME
ORDER BY REVENUE DESC;


// Task 66: Regional Sales Dashboard

SELECT
    R.REGION_NAME,
    S.STATE_NAME,
    CT.CITY_NAME,
    BR.BRANCH_NAME,
    BR.MANAGER_NAME,
    COUNT(*) AS TOTAL_TRANSACTIONS,
    SUM(F.QUANTITY) AS UNITS_SOLD,
    SUM(F.TOTAL_AMOUNT) AS REVENUE
FROM FACT_SALES F
JOIN DIM_BRANCH BR
    ON F.BRANCH_ID = BR.BRANCH_ID
JOIN DIM_CITY CT
    ON BR.CITY_ID = CT.CITY_ID
JOIN DIM_STATE S
    ON CT.STATE_ID = S.STATE_ID
JOIN DIM_REGION R
    ON S.REGION_ID = R.REGION_ID
GROUP BY
    R.REGION_NAME,
    S.STATE_NAME,
    CT.CITY_NAME,
    BR.BRANCH_NAME,
    BR.MANAGER_NAME
ORDER BY
    R.REGION_NAME,
    REVENUE DESC;


