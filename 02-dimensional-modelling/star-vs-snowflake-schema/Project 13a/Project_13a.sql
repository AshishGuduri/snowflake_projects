-- TASK 5 — Load Star Schema Fact Data
CREATE TABLE STG_SALES_TRANSACTIONS (
    TRANSACTION_ID   VARCHAR(50),
    TRANSACTION_DATE DATE,
    CUSTOMER_ID      NUMBER,
    STORE_ID         NUMBER,
    PRODUCT_ID       NUMBER,
    QUANTITY         NUMBER,
    UNIT_PRICE       NUMBER(10,2)
);

COPY INTO STG_SALES_TRANSACTIONS
FROM @P13_STAGE/sales_transactions.csv;

INSERT INTO STAR_FACT_SALES (TRANSACTION_ID, TRANSACTION_DATE, CUSTOMER_ID, STORE_KEY, PRODUCT_KEY, QUANTITY, TOTAL_AMOUNT)
SELECT
    t.TRANSACTION_ID,
    t.TRANSACTION_DATE,
    t.CUSTOMER_ID,
    s.STORE_KEY,
    p.PRODUCT_KEY,
    t.QUANTITY,
    t.QUANTITY * t.UNIT_PRICE AS TOTAL_AMOUNT
FROM STG_SALES_TRANSACTIONS t
JOIN STAR_DIM_STORE s   ON t.STORE_ID = s.STORE_ID
JOIN STAR_DIM_PRODUCT p ON t.PRODUCT_ID = p.PRODUCT_ID;

-- TASK 6 — Build Normalized Snowflake Schema Store Hierarchy
CREATE TABLE SNOW_DIM_REGION (
    REGION_KEY       NUMBER AUTOINCREMENT PRIMARY KEY,
    REGION_NAME      VARCHAR(50),
    REGIONAL_MANAGER VARCHAR(100)
);

CREATE TABLE SNOW_DIM_STORE (
    STORE_KEY   NUMBER AUTOINCREMENT PRIMARY KEY,
    STORE_ID    NUMBER,
    STORE_NAME  VARCHAR(100),
    CITY        VARCHAR(50),
    STATE       VARCHAR(50),
    REGION_KEY  NUMBER REFERENCES SNOW_DIM_REGION(REGION_KEY)
);

-- TASK 7 — Build Normalized Snowflake Schema Product Hierarchy
CREATE TABLE SNOW_DIM_CATEGORY (
    CATEGORY_KEY  NUMBER AUTOINCREMENT PRIMARY KEY,
    CATEGORY_NAME VARCHAR(50)
);

CREATE TABLE SNOW_DIM_SUBCATEGORY (
    SUBCATEGORY_KEY  NUMBER AUTOINCREMENT PRIMARY KEY,
    SUBCATEGORY_NAME VARCHAR(50),
    CATEGORY_KEY     NUMBER REFERENCES SNOW_DIM_CATEGORY(CATEGORY_KEY)
);

CREATE TABLE SNOW_DIM_PRODUCT (
    PRODUCT_KEY     NUMBER AUTOINCREMENT PRIMARY KEY,
    PRODUCT_ID      NUMBER,
    PRODUCT_NAME    VARCHAR(100),
    UNIT_PRICE      NUMBER(10,2),
    SUBCATEGORY_KEY NUMBER REFERENCES SNOW_DIM_SUBCATEGORY(SUBCATEGORY_KEY)
);

-- TASK 8 — Populate Snowflake Schema Normalized Dimensions
CREATE TABLE STG_REGIONS_STORES (
    STORE_ID         NUMBER,
    STORE_NAME       VARCHAR(100),
    CITY             VARCHAR(50),
    STATE            VARCHAR(50),
    REGION_NAME      VARCHAR(50),
    REGIONAL_MANAGER VARCHAR(100)
);

COPY INTO STG_REGIONS_STORES
FROM @P13_STAGE/regions_and_stores.csv;

CREATE TABLE STG_PRODUCT_HIERARCHY (
    PRODUCT_ID       NUMBER,
    PRODUCT_NAME     VARCHAR(100),
    SUBCATEGORY_NAME VARCHAR(50),
    CATEGORY_NAME    VARCHAR(50),
    UNIT_PRICE       NUMBER(10,2)
);

COPY INTO STG_PRODUCT_HIERARCHY
FROM @P13_STAGE/product_hierarchy.csv;

INSERT INTO SNOW_DIM_REGION (REGION_NAME, REGIONAL_MANAGER)
SELECT DISTINCT REGION_NAME, REGIONAL_MANAGER
FROM STG_REGIONS_STORES;

INSERT INTO SNOW_DIM_STORE (STORE_ID, STORE_NAME, CITY, STATE, REGION_KEY)
SELECT s.STORE_ID, s.STORE_NAME, s.CITY, s.STATE, r.REGION_KEY
FROM STG_REGIONS_STORES s
JOIN SNOW_DIM_REGION r ON s.REGION_NAME = r.REGION_NAME;

INSERT INTO SNOW_DIM_CATEGORY (CATEGORY_NAME)
