CREATE OR REPLACE TABLE BRONZE_RETAIL_TRANSACTIONS AS
SELECT
    RAW_DATA:pos_id::STRING           AS POS_ID,
    RAW_DATA:timestamp::TIMESTAMP_NTZ AS TIMESTAMP,
    RAW_DATA:hashed_email::STRING     AS HASHED_EMAIL,
    RAW_DATA:store_id::STRING         AS STORE_ID,
    RAW_DATA:cpg_brand::STRING        AS CPG_BRAND,
    RAW_DATA:basket_value::NUMBER(10,2) AS BASKET_VALUE,
    RAW_DATA:loyalty_tier::STRING     AS LOYALTY_TIER
FROM RAW_RETAIL_TRANSACTIONS;

CREATE OR REPLACE TABLE BRONZE_AD_EXPOSURES AS
SELECT
    RAW_DATA:ad_id::STRING            AS AD_ID,
    RAW_DATA:timestamp::TIMESTAMP_NTZ AS TIMESTAMP,
    RAW_DATA:hashed_email::STRING     AS HASHED_EMAIL,
    RAW_DATA:campaign_name::STRING    AS CAMPAIGN_NAME,
    RAW_DATA:channel::STRING          AS CHANNEL
FROM RAW_AD_EXPOSURES;

SELECT COUNT(*) AS TOTAL_RETAIL_RECORDS FROM BRONZE_RETAIL_TRANSACTIONS;

-- TASK 2: SILVER CLEAN ROOM OVERLAP & AGGREGATION LAYER
CREATE OR REPLACE TABLE SILVER_ATTRIBUTION_MATCH AS
SELECT
    pos.POS_ID,
    pos.STORE_ID,
    ad.CAMPAIGN_NAME,
    ad.CHANNEL,
    pos.BASKET_VALUE,
    DATEDIFF('hour', ad.TIMESTAMP, pos.TIMESTAMP) AS CONVERSION_HOURS
FROM BRONZE_RETAIL_TRANSACTIONS pos
JOIN BRONZE_AD_EXPOSURES ad
    ON pos.HASHED_EMAIL = ad.HASHED_EMAIL;

SELECT * FROM SILVER_ATTRIBUTION_MATCH
ORDER BY POS_ID;

-- TASK 3: AGGREGATE-ONLY DIFFERENTIAL PRIVACY VIEW (CLEAN ROOM GOVERNANCE)
CREATE OR REPLACE SECURE VIEW SECURE_GOLD_CAMPAIGN_ATTRIBUTION_PERFORMANCE AS
WITH FIRST_TOUCH AS (
    SELECT
        CAMPAIGN_NAME,
        CHANNEL,
        ROW_NUMBER() OVER (PARTITION BY CAMPAIGN_NAME ORDER BY TIMESTAMP ASC) AS RN
    FROM BRONZE_AD_EXPOSURES
)
SELECT
    s.CAMPAIGN_NAME,
    ft.CHANNEL,                              
    COUNT(DISTINCT s.POS_ID)   AS CONVERTED_USER_COUNT,
    SUM(s.BASKET_VALUE)        AS TOTAL_ATTRIBUTED_SALES,
    ROUND(AVG(s.BASKET_VALUE),2)        AS AVG_BASKET_VALUE
FROM SILVER_ATTRIBUTION_MATCH s
JOIN FIRST_TOUCH ft
    ON s.CAMPAIGN_NAME = ft.CAMPAIGN_NAME
   AND ft.RN = 1
GROUP BY s.CAMPAIGN_NAME, ft.CHANNEL
HAVING COUNT(DISTINCT s.POS_ID) >= 2;

SELECT * FROM SECURE_GOLD_CAMPAIGN_ATTRIBUTION_PERFORMANCE
ORDER BY CAMPAIGN_NAME, CHANNEL;

