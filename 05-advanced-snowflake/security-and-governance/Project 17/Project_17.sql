-- TASK 1: Bronze Storage Setup & Error Isolation
CREATE OR REPLACE DATABASE FINANCIAL_GOVERNANCE_DB;
CREATE OR REPLACE SCHEMA FINANCIAL_GOVERNANCE_DB.WEALTH_CORE;
USE DATABASE FINANCIAL_GOVERNANCE_DB;
USE SCHEMA WEALTH_CORE;
USE WAREHOUSE COMPUTE_WH;

CREATE OR REPLACE TABLE BRONZE_BANK_PAYLOADS (
    INGEST_ID   NUMBER AUTOINCREMENT START 1 INCREMENT 1 NOT NULL,
    PAYLOAD     VARIANT,
    LOADED_AT   TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE OR REPLACE TEMPORARY TABLE STG_RAW_TEXT_LINES (
    LINE_ID   NUMBER AUTOINCREMENT START 1 INCREMENT 1,
    RAW_TEXT  STRING
);

CREATE OR REPLACE STAGE STG_BANK_FILES;
CREATE OR REPLACE FILE FORMAT FF_RAW_LINE
    TYPE = 'CSV'
    FIELD_DELIMITER = NONE
    RECORD_DELIMITER = '\n'
    SKIP_HEADER = 0;

COPY INTO STG_RAW_TEXT_LINES (RAW_TEXT)
FROM @STG_BANK_FILES/bronze_bank_payloads.json
FILE_FORMAT = (FORMAT_NAME = FF_RAW_LINE);

INSERT INTO BRONZE_BANK_PAYLOADS (PAYLOAD, LOADED_AT)
SELECT TRY_PARSE_JSON(RAW_TEXT), CURRENT_TIMESTAMP()
FROM STG_RAW_TEXT_LINES
WHERE TRY_PARSE_JSON(RAW_TEXT) IS NOT NULL
ORDER BY LINE_ID;

SELECT COUNT(*) AS TOTAL_BRONZE_RECORDS FROM BRONZE_BANK_PAYLOADS;

CREATE OR REPLACE TABLE QUARANTINE_GOVERNANCE_PAYLOADS (
    QUARANTINE_ID     NUMBER AUTOINCREMENT START 1 INCREMENT 1 NOT NULL,
    RAW_RECORD_TEXT   STRING,
    REASON            STRING
);

INSERT INTO QUARANTINE_GOVERNANCE_PAYLOADS (RAW_RECORD_TEXT, REASON)
SELECT RAW_TEXT, 'MALFORMED_JSON_BODY'
FROM STG_RAW_TEXT_LINES
WHERE TRY_PARSE_JSON(RAW_TEXT) IS NULL;

SELECT * FROM QUARANTINE_GOVERNANCE_PAYLOADS;

-- TASK 2: Silver Layer Setup & RBAC Role Provisioning
CREATE OR REPLACE TABLE SILVER_BANK_TRANSACTIONS (
    TXN_ID           STRING,
    CLIENT_ID        NUMBER,
    CLIENT_SSN       STRING,
    REGION           STRING,
    ACCOUNT_NO       STRING,
    AMOUNT           NUMBER(18,2),
    STATUS           STRING,
    AML_RISK_SCORE   STRING
);

INSERT INTO SILVER_BANK_TRANSACTIONS
SELECT
    PAYLOAD:txn_id::STRING           AS TXN_ID,
    PAYLOAD:client_id::NUMBER        AS CLIENT_ID,
    PAYLOAD:client_ssn::STRING       AS CLIENT_SSN,
    PAYLOAD:region::STRING           AS REGION,
    PAYLOAD:account_no::STRING       AS ACCOUNT_NO,
    PAYLOAD:amount::NUMBER(18,2)     AS AMOUNT,
    PAYLOAD:status::STRING           AS STATUS,
    PAYLOAD:aml_risk_score::STRING   AS AML_RISK_SCORE
FROM BRONZE_BANK_PAYLOADS;

