-- TASK 6: END-TO-END CLEAN ROOM RECONCILIATION & COMPLIANCE CHECK
WITH SILVER_TOTAL AS (
    SELECT SUM(BASKET_VALUE) AS SILVER_MATCH_VAL
    FROM SILVER_ATTRIBUTION_MATCH
),
GOLD_TOTAL AS (
    SELECT SUM(TOTAL_ATTRIBUTED_SALES) AS GOLD_SHARED_VAL
    FROM SECURE_GOLD_CAMPAIGN_ATTRIBUTION_PERFORMANCE
),
PII_CHECK AS (
    SELECT COUNT(*) AS PII_COLUMN_COUNT
    FROM INFORMATION_SCHEMA.COLUMNS
    WHERE TABLE_SCHEMA = 'PARTNER_TELEMETRY'
      AND TABLE_NAME = 'SECURE_GOLD_CAMPAIGN_ATTRIBUTION_PERFORMANCE'
      AND COLUMN_NAME ILIKE '%HASHED_EMAIL%'
)
SELECT
    s.SILVER_MATCH_VAL,
    g.GOLD_SHARED_VAL,
    IFF(p.PII_COLUMN_COUNT = 0, FALSE, TRUE)                       AS PII_EXPOSURE_FLAG,
    IFF(s.SILVER_MATCH_VAL = g.GOLD_SHARED_VAL, TRUE, FALSE)       AS RECONCILED_FLAG
FROM SILVER_TOTAL s, GOLD_TOTAL g, PII_CHECK p;