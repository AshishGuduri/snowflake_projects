FROM STG_PRODUCT_HIERARCHY;

INSERT INTO SNOW_DIM_SUBCATEGORY (SUBCATEGORY_NAME, CATEGORY_KEY)
SELECT DISTINCT ph.SUBCATEGORY_NAME, c.CATEGORY_KEY
FROM STG_PRODUCT_HIERARCHY ph
JOIN SNOW_DIM_CATEGORY c ON ph.CATEGORY_NAME = c.CATEGORY_NAME;

INSERT INTO SNOW_DIM_PRODUCT (PRODUCT_ID, PRODUCT_NAME, UNIT_PRICE, SUBCATEGORY_KEY)
SELECT ph.PRODUCT_ID, ph.PRODUCT_NAME, ph.UNIT_PRICE, sc.SUBCATEGORY_KEY
FROM STG_PRODUCT_HIERARCHY ph
JOIN SNOW_DIM_SUBCATEGORY sc ON ph.SUBCATEGORY_NAME = sc.SUBCATEGORY_NAME;

SELECT COUNT(*) AS TOTAL_REGIONS FROM SNOW_DIM_REGION;            
